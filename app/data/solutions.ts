// Страницы-решения «Сложная разработка» (02.11.2026). Каждая страница отвечает на один запрос, с которым
// человек приходит к ИИ-ассистенту («кто сделает систему X и сколько стоит»): что делает система, для кого,
// интеграции, цены по уровням, сроки, кейс и вопросы. Только русский язык, только проверенные факты.
// Цены: из app/data/pricing.json и решения Айдара (карго от 600 000 ₸). Кейсы: только те, что открыто
// показаны в портфолио (app/data/projects.ts). Клиентов, которых не показываем, не упоминаем.

import { INDUSTRY_SOLUTIONS } from './solutions-industry';

export type SolutionGroup = 'sectors' | 'industry' | 'logistics' | 'sales' | 'public';

export interface SolutionTier {
  name: string;
  scope: string;
  price: string;
  term: string;
}

export interface SolutionCase {
  title: string;
  text: string;
  /** id из app/data/projects.ts, если проект есть в портфолио */
  projectId?: string;
  /** Своя картинка вместо скриншота проекта, например демо решения (подписываем в title, что это демо) */
  image?: string;
}

export interface SolutionFaq {
  q: string;
  a: string;
}

export interface Solution {
  slug: string;
  group: SolutionGroup;
  /** Что болит у клиента (для страницы «Производство»): строка до решения */
  pain?: string;
  /** Что добавит ИИ в этой сфере: 3-4 конкретных применения (Айдар, 02.11: «внедрение ИИ для каждой сферы») */
  ai?: string[];
  // Подробные страницы (с 02.11, направления из отчёта «ИИ для заводов Запад и Казахстан»): блоки ниже необязательные.
  /** Как это работает по шагам, идёт и в разметку HowTo */
  steps?: { title: string; text: string }[];
  /** Живой пример: что прислал клиент и что получилось на выходе */
  example?: { title: string; input: string; inputNote: string; output: { label: string; value: string }[]; outputNote: string };
  /** Что замеряем на пилоте: до и после */
  metrics?: string[];
  /** Что нужно от клиента для старта */
  requirements?: string[];
  /** Как устроено внутри: компоненты системы для технического директора и программиста 1С */
  architecture?: { label: string; title: string; text: string }[];
  /** Проверки, которые проходит каждый документ, прежде чем попасть в учётную систему */
  checks?: string[];
  /** Безопасность и хранение данных */
  security?: string[];
  /** План пилота по неделям */
  plan?: { period: string; title: string; text: string }[];
  /** Пример расчёта окупаемости: допущения подписаны, клиент подставляет свои цифры */
  roi?: { intro: string; rows: { label: string; value: string }[]; result: string; note: string };
  /** Сценарии по отраслям: как выглядит задача у бетона, металла, пищевых и т.д. */
  scenarios?: { title: string; text: string }[];
  /** Термины и аббревиатуры (IDP, OCR, LLM...): по ним ищут в поиске и спрашивают ИИ, идёт в разметку DefinedTermSet */
  glossary?: { term: string; text: string }[];
  /** Сравнение с западными аналогами: честно, с пометкой, что цифры заявлены вендорами */
  compare?: { intro: string; rows: { name: string; what: string; price: string }[]; note: string };
  /** H1 страницы */
  title: string;
  /** Короткое название для карточек и меню */
  short: string;
  /** Одна строка для карточки на общей странице */
  card: string;
  metaTitle: string;
  metaDescription: string;
  /** Первый абзац: сразу ответ на запрос (что, для кого, цена от, срок) */
  lead: string;
  /** Нижняя цена в тенге для разметки Offer */
  priceFrom: number;
  audience: string[];
  features: string[];
  integrations: string[];
  tiers: SolutionTier[];
  cases: SolutionCase[];
  faq: SolutionFaq[];
  related: string[];
}

