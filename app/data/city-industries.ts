// FAQ-текст зависит от cityLocative (родительный/предложный падеж города),
// которого нет в CityIndustryProfile — он приходит из CityEntry в cities.ts.
export function resolveCityFaq(citySlug: string, cityLocative: string) {
  const profile = cityIndustryProfiles[citySlug];
  if (!profile) return null;
  const serviceNames = profile.services.map((service) => service.name).join(', ');
  return {
    question: `Можете разработать систему под задачи местного бизнеса ${cityLocative}?`,
    answer: `Да, работаем и с такими задачами. Знаем специфику ${cityLocative} — ${profile.industries.join(', ')} — и чаще всего это: ${serviceNames}. Но это не готовое решение под копирку: считаем объём и цену после короткого брифа про ваши процессы.`,
  };
}
